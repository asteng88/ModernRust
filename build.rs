//! Auto-discovers every `.svg` file under `assets/icons/` at compile time and generates
//! `Icon`, `Icon::ALL`, `Icon::name()`, `Icon::category()`, and `Icon::svg_source()`.
//!
//! To add a new icon for any Rust app, simply drop a `24x24` `.svg` file into
//! `assets/icons/<category>/<snake_name>.svg` and rebuild.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn to_pascal(stem: &str) -> String {
    stem.split(|c: char| c == '_' || c == '-' || c == ' ')
        .filter(|s| !s.is_empty())
        .map(|part| {
            let mut ch = part.chars();
            match ch.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + &ch.as_str().to_ascii_lowercase(),
                None => String::new(),
            }
        })
        .collect()
}

fn to_label(stem: &str) -> String {
    stem.split(|c: char| c == '_' || c == '-')
        .filter(|s| !s.is_empty())
        .map(|part| {
            if part.eq_ignore_ascii_case("pdf") {
                "PDF".to_string()
            } else {
                let mut ch = part.chars();
                match ch.next() {
                    Some(first) => first.to_ascii_uppercase().to_string() + ch.as_str(),
                    None => String::new(),
                }
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn collect_svgs(dir: &Path, root: &Path, out: &mut BTreeMap<String, (String, String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            println!("cargo:rerun-if-changed={}", path.display());
            collect_svgs(&path, root, out);
        } else if path.extension().is_some_and(|e| e.eq_ignore_ascii_case("svg")) {
            println!("cargo:rerun-if-changed={}", path.display());
            let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or_default();
            if stem.is_empty() {
                continue;
            }
            let variant = to_pascal(stem);
            let label = to_label(stem);
            let category = path
                .parent()
                .and_then(|p| p.strip_prefix(root).ok())
                .and_then(|rel| rel.to_str())
                .unwrap_or("core")
                .replace('\\', "/");
            let category = if category.is_empty() { "core".to_string() } else { category };
            out.insert(variant, (label, category, path));
        }
    }
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let icons_root = manifest_dir.join("assets").join("icons");
    println!("cargo:rerun-if-changed={}", icons_root.display());

    let mut found = BTreeMap::new();
    collect_svgs(&icons_root, &icons_root, &mut found);

    let mut code = String::new();
    code.push_str("// @generated by build.rs from assets/icons/**/*.svg — do not edit by hand.\n\n");
    code.push_str("#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]\n");
    code.push_str("pub enum Icon {\n");
    for variant in found.keys() {
        code.push_str(&format!("    {variant},\n"));
    }
    code.push_str("}\n\n");

    code.push_str("impl Icon {\n");
    code.push_str("    pub const ALL: &'static [Self] = &[\n");
    for variant in found.keys() {
        code.push_str(&format!("        Self::{variant},\n"));
    }
    code.push_str("    ];\n\n");

    code.push_str("    pub fn name(self) -> &'static str {\n");
    code.push_str("        match self {\n");
    for (variant, (label, _, _)) in &found {
        code.push_str(&format!("            Self::{variant} => {label:?},\n"));
    }
    code.push_str("        }\n");
    code.push_str("    }\n\n");

    code.push_str("    pub fn category(self) -> &'static str {\n");
    code.push_str("        match self {\n");
    for (variant, (_, category, _)) in &found {
        code.push_str(&format!("            Self::{variant} => {category:?},\n"));
    }
    code.push_str("        }\n");
    code.push_str("    }\n\n");

    code.push_str("    pub fn svg_source(self) -> &'static str {\n");
    code.push_str("        match self {\n");
    for (variant, (_, _, path)) in &found {
        let abs = path.to_string_lossy().replace('\\', "/");
        code.push_str(&format!("            Self::{variant} => include_str!({abs:?}),\n"));
    }
    code.push_str("        }\n");
    code.push_str("    }\n");
    code.push_str("}\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("generated_icons.rs"), code).expect("write generated_icons.rs");
}
